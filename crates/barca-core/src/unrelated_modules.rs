/// Whether `module` (a dotted name as imported) belongs to one of the lists above.
pub fn is_unrelated(module: &str) -> bool {
    let root = module.split('.').next().unwrap_or(module);
    STDLIB.contains(&root) || THIRD_PARTY.contains(&root)
}
