import { existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'

const root = fileURLToPath(new URL('../..', import.meta.url))
const fixture = fileURLToPath(new URL('./fixture', import.meta.url))
const binary = process.env.BARCA_BIN ?? (existsSync(`${root}/target-local/debug/barca`) ? `${root}/target-local/debug/barca` : `${root}/target/debug/barca`)

test('bootstrap, authenticated execution, one-time token display, reload, disconnect and revocation', async ({ page, context }) => {
  const code = execFileSync(binary, ['tokens', 'bootstrap'], { cwd: fixture, encoding: 'utf8' }).trim()
  await context.addCookies([{ name: 'ambient', value: 'must-not-send', url: 'http://127.0.0.1:5276' }])
  const streams: boolean[] = []
  page.on('request', request => {
    if (/\/runs\/[^/]+\/events$/.test(new URL(request.url()).pathname)) streams.push(!!request.headers()['authorization']?.startsWith('Bearer ') && !request.headers()['cookie'])
  })
  await page.goto('/ui/')
  await expect(page.getByRole('heading', { name: 'Connect to barca' })).toBeVisible()
  await page.getByLabel('API token or bootstrap code').fill(code)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Assets', exact: true })).toBeVisible()
  await page.goto('/ui/#/graph')
  await page.getByText('say_hello', { exact: true }).first().click()
  await page.getByRole('banner').getByRole('button', { name: 'Run', exact: true }).click()
  await expect(page.getByRole('complementary', { name: /inspector$/ })).toContainText('hello from authenticated stream', { timeout: 30_000 })
  expect(streams.length).toBeGreaterThan(0)
  expect(streams.every(Boolean)).toBe(true)
  await page.getByRole('link', { name: 'API tokens', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('laptop')
  await expect(page.getByText('No expiry selected: this token will stay valid until revoked.')).toBeVisible()
  await page.getByRole('button', { name: 'Create token', exact: true }).click()
  await expect(page.locator('.barca-token-secret')).toBeVisible()
  const token = await page.locator('.barca-token-secret').innerText()
  expect(token.startsWith('barca_api_v1_')).toBe(true)
  await expect(page.getByText('This token has no expiry.')).toBeVisible()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('.barca-token-secret')).toHaveCount(0)
  await page.getByLabel('Name', { exact: true }).fill('temporary')
  await page.getByLabel('Expiry (optional, your local time)').fill('2030-01-01T12:00')
  await page.getByRole('button', { name: 'Create token', exact: true }).click()
  await expect(page.locator('.barca-token-secret')).toBeVisible()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.locator('.barca-token-row').filter({ hasText: 'temporary' })).toContainText('2030')
  await page.getByRole('button', { name: 'Revoke temporary' }).click()
  await expect(page.getByRole('button', { name: 'Revoke temporary' })).toHaveCount(0)
  await page.locator('aside').getByRole('button', { name: 'Disconnect', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Connect to barca' })).toBeVisible()
  expect(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.startsWith('barca:connection:')))).toBe(false)
  await page.getByLabel('API token or bootstrap code').fill(token)
  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'API tokens', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'API tokens', exact: true })).toBeVisible()
  await expect(page.locator('.barca-token-secret')).toHaveCount(0)
  expect(await page.evaluate(() => Object.keys(localStorage).some(key => key.startsWith('barca:connection:')))).toBe(false)
  expect(page.url().includes(token) || page.url().includes(code)).toBe(false)
  await page.getByRole('button', { name: 'Revoke bootstrap connection' }).click()
  await expect(page.getByRole('button', { name: 'Revoke bootstrap connection' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Revoke laptop' }).click()
  await expect(page.getByRole('heading', { name: 'Connect to barca' })).toBeVisible()
  expect(await page.evaluate(() => Object.keys(sessionStorage).some(key => key.startsWith('barca:connection:')))).toBe(false)
})
