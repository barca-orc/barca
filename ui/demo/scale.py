"""Generate and seed a project at the size of a real data platform, to use the UI against.

    python3 ui/demo/scale.py                      # 10,000 nodes, a 20,000-key asset
    python3 ui/demo/scale.py --nodes 30000 --keys 100000
    python3 ui/demo/scale.py --generate-only      # write the sources, run nothing

Writes `ui/demo/scale/` (gitignored), then seeds it through barca's own commands: a full
`get`, every check task, an edit that leaves some assets stale, and a run history. Then:

    cd ui/demo/scale && PYTHONPATH=../../../python ../../../target/debug/barca serve --no-schedule

The project is sixteen domains (one source file each), every one grouped domain → stage
(raw, staging, core, marts) → entity, so the group tree is three deep. Stages read the one
before; a domain's raw stage reads other domains' marts, so the graph crosses files. About
one asset in four has a data-quality check task. Failures are deterministic and of the kinds
a data engineer meets: a missing column, a schema change, an upstream API error, a division
by zero, failed checks, and some keys of the big partitioned asset. Their downstream does not
run. A few hundred nodes sleep, so durations vary.
"""

from __future__ import annotations

import argparse
import os
import random
import re
import shutil
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = Path(__file__).resolve().parent / "scale"

DOMAINS = {
    "web": ["sessions", "pageviews", "clicks", "experiments", "referrers", "devices"],
    "mobile": ["installs", "screens", "crashes", "pushes", "versions", "attribution"],
    "crm": ["accounts", "contacts", "leads", "opportunities", "activities", "owners"],
    "billing": ["invoices", "subscriptions", "plans", "credits", "taxes", "dunning"],
    "payments": ["charges", "refunds", "disputes", "payouts", "fees", "methods"],
    "catalog": ["products", "variants", "prices", "categories", "bundles", "images"],
    "inventory": ["stock", "warehouses", "transfers", "counts", "reservations", "suppliers"],
    "logistics": ["shipments", "carriers", "routes", "returns", "delays", "labels"],
    "marketing": ["campaigns", "audiences", "emails", "budgets", "touches", "coupons"],
    "ads": ["impressions", "spend", "keywords", "creatives", "bids", "conversions"],
    "support": ["tickets", "agents", "macros", "csat", "slas", "chats"],
    "finance": ["ledger", "revenue", "costs", "forecasts", "fx", "close"],
    "risk": ["fraud", "chargebacks", "kyc", "limits", "alerts", "reviews"],
    "features": ["user_features", "item_features", "context", "embeddings", "labels", "snapshots"],
    "models": ["churn", "ltv", "ranking", "forecast", "propensity", "anomaly"],
    "reporting": ["exec", "weekly", "board", "ops", "growth", "unit_economics"],
}
STAGES = ["raw", "staging", "core", "marts"]

# Deterministic failures, each the kind of thing that breaks a real pipeline.
FAILURES = [
    ("KeyError", "raise KeyError('currency')"),
    ("schema", "raise ValueError(\"column 'amount' changed type: expected float64, got string\")"),
    (
        "upstream",
        "raise RuntimeError('GET https://api.partner.example/v2/export returned 503 Service Unavailable after 3 retries')",
    ),
    ("zero", "rows = 0\n    return {'node': NAME, 'n': 100 / rows}"),
    (
        "memory",
        "raise MemoryError('could not allocate 12.4 GiB for the join of orders and line_items')",
    ),
]
CHECK_FAILURES = [
    "null rate of customer_id is 12.3%, above the 5% threshold",
    "row count fell 64% day over day (182,331 → 65,640)",
    "4,102 duplicate primary keys in order_id",
    "freshness: newest updated_at is 31h old, expected under 6h",
]

HEADER = '''"""Generated by ui/demo/scale.py: the {domain} domain."""
import time

from barca import Schedule, asset, collect, group, partitions, sensor, task


def _n(*values):
    """A number from any upstream values, so every value depends on its inputs."""
    total = 1
    for value in values:
        if isinstance(value, dict):
            total += int(value.get("n", 1)) % 997
        elif isinstance(value, list):
            total += len(value)
    return total

'''


def generate(
    dest: Path, n_nodes: int, keys: int, seed: int, *, clean: bool = False
) -> list[tuple[str, str]]:
    """Write the sources; the (file, node) of every failure. `clean` writes the same project
    with no failures: the same seed draws the same graph either way."""
    rng = random.Random(seed)
    dest.mkdir(parents=True, exist_ok=True)
    failing: list[tuple[str, str]] = []
    domains = list(DOMAINS)
    # Each entity of each stage gets `per` assets; a quarter of the assets get a check.
    per = max(1, round(n_nodes / (len(domains) * len(STAGES) * 6 * 1.25)))
    marts: dict[str, list[str]] = {}
    totals = {"assets": 0, "tasks": 0, "groups": 0}

    for d_index, domain in enumerate(domains):
        out: list[str] = [HEADER.format(domain=domain)]
        imports: set[tuple[str, str]] = set()
        groups: list[str] = []
        stage_nodes: dict[str, list[str]] = {}
        special: list[str] = []  # the partitioned assets, grouped with the first raw entity

        if domain in ("web", "mobile"):
            out.append(
                f'@sensor(freshness=Schedule("*/15 * * * *"))\n'
                f"def {domain}__feed() -> tuple[bool, str]:\n"
                f'    return True, "2026-10-29T12"\n\n\n'
            )
        if domain == "web":
            out.append(
                'DAYS = [f"2025-{m:02d}-{d:02d}" for m in range(1, 13) for d in range(1, 29)]\n\n\n'
                '@asset(partitions={"day": partitions(DAYS)})\n'
                "def web__raw__events_by_day(day: str) -> dict:\n"
                '    return {"day": day, "n": len(day)}\n\n\n'
                '@asset(inputs={"days": collect(web__raw__events_by_day)})\n'
                "def web__raw__events_rollup(days: list) -> dict:\n"
                '    return {"n": len(days)}\n\n\n'
            )
            special = ["web__raw__events_by_day", "web__raw__events_rollup"]
            stage_nodes.setdefault("raw", []).append(
                "web__raw__events_rollup"
            )  # the keys reach the rest only through it
        if domain == "billing":
            out.append(
                f'ACCOUNTS = [f"acct_{{i:06d}}" for i in range({keys})]\n\n\n'
                '@asset(partitions={"account": partitions(ACCOUNTS)})\n'
                "def billing__raw__invoices_by_account(account: str) -> dict:\n"
                + (
                    ""
                    if clean
                    else "    if int(account[5:]) % 211 == 7:\n"
                    '        raise ValueError(f"invoice export for {account} has 3 rows with a negative total")\n'
                )
                + '    return {"account": account, "n": int(account[5:]) % 97}\n\n\n'
                '@asset(inputs={"invoices": collect(billing__raw__invoices_by_account)})\n'
                "def billing__raw__invoice_totals(invoices: list) -> dict:\n"
                '    return {"n": len(invoices)}\n\n\n'
            )
            special = ["billing__raw__invoices_by_account", "billing__raw__invoice_totals"]
            stage_nodes.setdefault("raw", []).append(
                "billing__raw__invoice_totals"
            )  # the keys reach the rest only through it

        stage_groups: list[str] = []
        for s_index, stage in enumerate(STAGES):
            entity_groups: list[str] = []
            for entity in DOMAINS[domain]:
                members: list[str] = []
                for i in range(per):
                    name = f"{domain}__{stage}__{entity}_{i:02d}"
                    ups: list[str] = []
                    if s_index > 0:
                        before = stage_nodes.get(STAGES[s_index - 1], [])
                        same = [n for n in before if f"__{entity}_" in n]
                        ups = (
                            rng.sample(same, min(len(same), rng.choice([1, 1, 2]))) if same else []
                        )
                        others = [n for n in before if n not in ups]
                        if others and rng.random() < 0.5:
                            ups.append(rng.choice(others))
                    elif d_index > 1 and rng.random() < 0.25:
                        source = rng.choice(domains[:d_index])
                        if marts.get(source):
                            upstream = rng.choice(marts[source])
                            ups = [upstream]
                            imports.add((source, upstream))
                    elif domain in ("web", "mobile") and i == 0:
                        ups = [f"{domain}__feed"]
                    params = [f"x{j}" for j in range(len(ups))]
                    kwargs = []
                    if ups:
                        kwargs.append(
                            "inputs={" + ", ".join(f'"{p}": {u}' for p, u in zip(params, ups)) + "}"
                        )
                    roll = rng.random()
                    if stage == "marts" and roll < 0.04:
                        kwargs.append('freshness=Schedule("0 6 * * *")')
                    body = f"    return {{'node': NAME, 'n': _n({', '.join(params)})}}"
                    fail = rng.random()
                    if fail < 0.004:
                        _, code = rng.choice(FAILURES)
                        if not clean:
                            body = f"    {code}"
                            failing.append((f"{domain}.py", name))
                    sleep = rng.random()
                    pre = ""
                    if sleep < 0.03:
                        pre = f"    time.sleep({rng.choice([0.2, 0.5, 1.0, 2.5])})\n"
                    out.append(
                        f"@asset({', '.join(kwargs)})\n"
                        f"def {name}({', '.join(params)}) -> dict:\n"
                        f"{pre}{body.replace('NAME', repr(name))}\n\n\n"
                    )
                    members.append(name)
                    stage_nodes.setdefault(stage, []).append(name)
                    totals["assets"] += 1
                    if rng.random() < 0.25:
                        check = f"check__{name}"
                        message = rng.choice(CHECK_FAILURES)
                        fails = rng.random() < 0.03 and not clean
                        if fails:
                            failing.append((f"{domain}.py", check))
                        out.append(
                            f'@task(inputs={{"value": {name}}})\n'
                            f"def {check}(value: dict) -> None:\n"
                            + (
                                f"    raise AssertionError({message!r})\n\n\n"
                                if fails
                                else "    assert value['n'] >= 0\n\n\n"
                            )
                        )
                        members.append(check)
                        totals["tasks"] += 1
                if stage == "raw" and entity == DOMAINS[domain][0]:
                    members = special + members
                assets = [m for m in members if not m.startswith("check__")]
                var = f"g_{stage}_{entity}"
                groups.append(
                    f"{var} = group(\n    {entity.replace('_', ' ').title()!r},\n"
                    f"    members=[{', '.join(members)}],\n    output={assets[-1]},\n"
                    f"    description='{entity.replace('_', ' ')} at the {stage} stage of {domain}',\n)\n\n"
                )
                entity_groups.append(var)
                totals["groups"] += 1
            var = f"g_{stage}"
            groups.append(
                f"{var} = group(\n    {stage.title()!r},\n    members=[{', '.join(entity_groups)}],\n"
                f"    output={entity_groups[-1]},\n    description='The {stage} stage of {domain}',\n)\n\n"
            )
            stage_groups.append(var)
            totals["groups"] += 1
        marts[domain] = stage_nodes["marts"]
        feed = [f"{domain}__feed"] if domain in ("web", "mobile") else []
        groups.append(
            f"g_{domain} = group(\n    {domain.title()!r},\n    members=[{', '.join(feed + stage_groups)}],\n"
            f"    output={stage_groups[-1]},\n    description='Everything in the {domain} domain',\n)\n"
        )
        totals["groups"] += 1
        imp = "".join(f"from {f} import {n}\n" for f, n in sorted(imports))
        text = (
            out[0]
            + imp
            + "\n\n"
            + "".join(out[1:])
            + "\n# Organizational hierarchy: never changes dependencies or cache keys.\n"
            + "".join(groups)
        )
        (dest / f"{domain}.py").write_text(text)
    (dest / "barca.toml").write_text("")
    print(
        f"generated {totals['assets']} assets, {totals['tasks']} check tasks and {totals['groups']} groups "
        f"in {len(domains)} files; {len(failing)} fail; one asset has {keys} keys",
        flush=True,
    )
    if not clean:
        failing.append(("billing.py", "billing__raw__invoices_by_account"))
    return failing


def seed(dest: Path, barca: str, args: argparse.Namespace) -> None:
    """Fill the metadata DB the way a platform fills up, through barca's own commands."""
    rng = random.Random(args.seed)
    env = {**os.environ, "PYTHONPATH": str(ROOT / "python")}

    def call(*argv: str) -> int:
        t = time.time()
        r = subprocess.run(
            [barca, *argv],
            cwd=dest,
            env=env,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )
        shown = " ".join(a if len(a) < 60 else a[:57] + "..." for a in argv)
        print(f"  barca {shown}: exit {r.returncode} in {time.time() - t:.1f}s", flush=True)
        if r.returncode not in (0, 1):
            print(r.stderr[-2000:], flush=True)
        return r.returncode

    started = time.time()
    files = sorted(p.name for p in dest.glob("*.py"))
    # 1. A healthy platform: everything computed, every check passing.
    call("get")
    for f in files:
        checks = re.findall(r"^def (check__\w+)\(", (dest / f).read_text(), re.MULTILINE)
        call("run", ",".join(checks), f)
    # 2. Things break. The same graph with failures in it; each failing node is run, as its
    # schedule or its owner would, and fails. A failed step stops its run, so one run each.
    # Their downstream keeps the last good version, now stale.
    failing = generate(dest, args.nodes, args.keys, args.seed)
    for f, name in failing:
        call("run" if name.startswith("check__") else "get", name, f)
    # 3. Edits: a few raw assets change, and their downstream is stale until the next get.
    for f in ("crm.py", "catalog.py"):
        path = dest / f
        text = path.read_text()
        names = re.findall(r"^def (\w+__raw__\w+)\(", text, re.MULTILINE)
        for name in rng.sample(names, min(3, len(names))):
            text = re.sub(
                rf"(def {name}\(.*\n(?:    time\.sleep.*\n)?    return \{{)",
                r"\1'edited': 1, ",
                text,
                count=1,
            )
        path.write_text(text)
    # 4. A history of refreshes.
    assets = [
        (f, n)
        for f in files
        for n in re.findall(r"^def (\w+__\w+__\w+)\(", (dest / f).read_text(), re.MULTILINE)
    ]
    for _ in range(args.runs):
        f, name = rng.choice(assets)
        call("get", name, f, "--refresh", name)
    print(f"seeded in {time.time() - started:.0f}s", flush=True)


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--nodes", type=int, default=10_000)
    ap.add_argument("--keys", type=int, default=20_000)
    ap.add_argument("--runs", type=int, default=20)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--dest", type=Path, default=DEST)
    ap.add_argument("--generate-only", action="store_true")
    ap.add_argument(
        "--barca", default=os.environ.get("BARCA_BIN", str(ROOT / "target/debug/barca"))
    )
    a = ap.parse_args()
    if a.dest.exists() and not a.generate_only:
        shutil.rmtree(a.dest)
    generate(a.dest, a.nodes, a.keys, a.seed, clean=not a.generate_only)
    if not a.generate_only:
        seed(a.dest, a.barca, a)


if __name__ == "__main__":
    main()
