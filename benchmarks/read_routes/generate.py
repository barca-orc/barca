"""Generate the read-routes fixture: a 300-asset barca project shaped like a real one.

    python benchmarks/read_routes/generate.py DEST [--keys 200000] [--assets 300]

The project has six source files of about 50 nodes each, wired in layers so that the DAG is
about eight deep with fan-out and fan-in; sensors and `Schedule(...)` nodes; a parquet, json
and pickle mix; small partitioned assets (regions, months); and one partitioned asset with
`--keys` keys (the user who reported the slow state view has about 200k retailers). Its keys
come from an expression, so barca evaluates them in Python when it plans, as it would for keys
read from a table.

`bench.sh` seeds a history by running the project, then times every read route and CLI
command. Nothing here depends on the network.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

FILES = ["ingest", "retail", "finance", "marketing", "ops", "reports"]
FORMATS = ["json", "json", "pickle", "parquet"]


def body(fmt: str, inputs: list[str], name: str) -> str:
    """A cheap function body that returns a value serialized as `fmt`."""
    total = " + ".join(f"_n({p})" for p in inputs) or "1"
    if fmt == "parquet":
        return (
            f"    import pyarrow as pa\n"
            f"    n = {total}\n"
            f"    return pa.table({{'id': list(range(20)), 'v': [float(n)] * 20, 'name': ['{name}'] * 20}})\n"
        )
    if fmt == "pickle":
        return f"    return {{'node': '{name}', 'n': {total}, 'set': frozenset([1, 2])}}\n"
    return f"    return {{'node': '{name}', 'n': {total}}}\n"


HEADER = '''"""Generated by benchmarks/read_routes/generate.py."""
from barca import asset, sensor, task, collect, partitions, partitions_from, Schedule, Manual


def _n(value):
    """Turn any upstream value into a number, whatever its format."""
    if isinstance(value, dict):
        return int(value.get("n", 1)) % 1000
    if isinstance(value, list):
        return len(value)
    try:
        return value.num_rows
    except AttributeError:
        return 1

'''


def generate(dest: Path, n_assets: int = 300, keys: int = 200_000, seed: int = 7) -> None:
    rng = random.Random(seed)
    dest.mkdir(parents=True, exist_ok=True)
    per_file = n_assets // len(FILES)
    # (file, name) of every node, by layer, so inputs only point to earlier layers.
    names: list[tuple[str, str]] = []
    sources: dict[str, list[str]] = {f: [HEADER] for f in FILES}
    imports: dict[str, set[tuple[str, str]]] = {f: set() for f in FILES}
    layers = 8

    def emit(file: str, text: str) -> None:
        sources[file].append(text)

    # Sensors: one per file for the first three files.
    for f in FILES[:3]:
        emit(
            f,
            f'@sensor(freshness=Schedule("*/5 * * * *"))\n'
            f"def {f}_feed() -> tuple[bool, str]:\n"
            f'    return True, "v1"\n\n\n',
        )

    # The partitioned assets.
    emit(
        "retail",
        f'RETAILERS = [f"r{{i:06d}}" for i in range({keys})]\n\n\n'
        '@asset(partitions={"retailer": partitions(RETAILERS)}, serializer="json")\n'
        "def retailer_sales(retailer: str) -> dict:\n"
        '    return {"retailer": retailer, "n": len(retailer)}\n\n\n'
        '@asset(inputs={"sales": collect(retailer_sales)}, serializer="pickle")\n'
        "def retailer_rollup(sales: list) -> dict:\n"
        '    return {"n": len(sales)}\n\n\n',
    )
    emit(
        "finance",
        '@asset(partitions={"region": partitions(["emea", "amer", "apac", "latam", "anz"])})\n'
        "def region_ledger(region: str) -> dict:\n"
        '    return {"region": region, "n": 5}\n\n\n'
        '@asset(partitions={"region": partitions_from(region_ledger)})\n'
        "def region_margin(region: str, region_ledger: dict) -> dict:\n"
        '    return {"n": region_ledger["n"] * 2}\n\n\n'
        '@asset(inputs={"m": collect(region_margin)})\n'
        "def margin_total(m: list) -> dict:\n"
        '    return {"n": len(m)}\n\n\n',
    )
    emit(
        "marketing",
        'MONTHS = [f"2025-{m:02d}" for m in range(1, 13)] + [f"2026-{m:02d}" for m in range(1, 13)]\n\n\n'
        '@asset(partitions={"month": partitions(MONTHS)}, serializer="parquet")\n'
        "def monthly_spend(month: str):\n"
        "    import pyarrow as pa\n"
        '    return pa.table({"month": [month], "spend": [1.0]})\n\n\n',
    )
    special = 6
    for i in range(n_assets - special):
        f = FILES[i // per_file] if i // per_file < len(FILES) else FILES[-1]
        layer = min(layers - 1, (i % per_file) * layers // per_file)
        name = f"{f}_{i:03d}"
        candidates = [(nf, nn, nl) for nf, nn, nl in names if nl < layer]
        fan_in = 0 if layer == 0 else rng.choice([1, 1, 2, 2, 3, 4])
        ups = rng.sample(candidates, min(fan_in, len(candidates))) if candidates else []
        fmt = rng.choice(FORMATS)
        if layer == 0 and i % 17 == 0:
            ups = []
            sensor_file = FILES[(i // per_file) % 3]
            ups_names = [f"{sensor_file}_feed"]
            if sensor_file != f:
                imports[f].add((sensor_file, f"{sensor_file}_feed"))
            params = ["feed"]
            inputs = f'inputs={{"feed": {sensor_file}_feed}}'
            fmt = "json"
        else:
            params = [f"x{j}" for j in range(len(ups))]
            parts = []
            for p, (uf, un, _) in zip(params, ups):
                if uf != f:
                    imports[f].add((uf, un))
                parts.append(f'"{p}": {un}')
            inputs = f"inputs={{{', '.join(parts)}}}" if parts else ""
            ups_names = [u[1] for u in ups]
        kwargs = [inputs] if inputs else []
        if fmt != "json":
            kwargs.append(f'serializer="{fmt}"')
        if i % 23 == 5:
            kwargs.append('freshness=Schedule("0 * * * *")')
        elif i % 41 == 9:
            kwargs.append("freshness=Manual")
        sig = ", ".join(params)
        emit(f, f"@asset({', '.join(kwargs)})\ndef {name}({sig}):\n{body(fmt, params, name)}\n\n")
        names.append((f, name, layer))
        _ = ups_names
    # Some tasks reading leaves.
    for k, f in enumerate(FILES):
        leaves = [n for nf, n, nl in names if nf == f and nl == layers - 1][:2]
        if leaves:
            params = ", ".join(f"x{j}" for j in range(len(leaves)))
            inputs = ", ".join(f'"x{j}": {n}' for j, n in enumerate(leaves))
            emit(
                f,
                f"@task(inputs={{{inputs}}})\ndef publish_{f}({params}) -> None:\n    pass\n\n\n",
            )
    for f in FILES:
        lines = sources[f]
        imp = "".join(f"from {uf} import {un}\n" for uf, un in sorted(imports[f]))
        text = lines[0] + imp + "\n\n" + "".join(lines[1:])
        (dest / f"{f}.py").write_text(text)
    (dest / "barca.toml").write_text("")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("dest", type=Path)
    ap.add_argument("--assets", type=int, default=300)
    ap.add_argument("--keys", type=int, default=200_000)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    generate(a.dest, a.assets, a.keys, a.seed)


if __name__ == "__main__":
    main()
