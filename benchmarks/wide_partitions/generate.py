"""Generate the wide-partitions fixture: many partitioned nodes with many keys each.

    python benchmarks/wide_partitions/generate.py DEST [--files 10] [--nodes 100] [--keys 1200]

Each file is a chain of `--nodes` assets in blocks of 25: a source with `--keys` keys (from an
expression, so barca evaluates them in Python when it plans), 23 assets keyed by
`partitions_from` the one before, and a `collect` fan-in. The default is 1,000 nodes with
1.2M keys between them, the shape at which the web UI was unusable before 0.34.1.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def pipeline(f: int, nodes: int, keys: int) -> str:
    lines = [
        '"""Generated by benchmarks/wide_partitions/generate.py."""',
        "from barca import asset, collect, partitions, partitions_from",
        "",
        f'KEYS = [f"k{{i:05d}}" for i in range({keys})]',
        "",
    ]
    for i in range(nodes):
        name, prev = f"p{f}_a{i}", f"p{f}_a{i - 1}"
        if i % 25 == 0:
            lines += [
                '@asset(partitions={"key": partitions(KEYS)})',
                f"def {name}(key: str) -> int:",
                "    return len(key)",
            ]
        elif i % 25 == 24:
            lines += [
                f'@asset(inputs={{"xs": collect({prev})}})',
                f"def {name}(xs: list) -> int:",
                "    return sum(xs)",
            ]
        else:
            lines += [
                f'@asset(partitions={{"key": partitions_from({prev})}})',
                f"def {name}(key: str, {prev}: int) -> int:",
                f"    return {prev} + 1",
            ]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dest", type=Path)
    parser.add_argument("--files", type=int, default=10)
    parser.add_argument("--nodes", type=int, default=100, help="nodes per file")
    parser.add_argument("--keys", type=int, default=1200, help="keys per partitioned node")
    args = parser.parse_args()
    args.dest.mkdir(parents=True, exist_ok=True)
    for f in range(args.files):
        (args.dest / f"pipe_{f:02d}.py").write_text(pipeline(f, args.nodes, args.keys))


if __name__ == "__main__":
    main()
