"""The 116-node planning pipeline (#250), small deterministic size, run end to end.

The project is generated by benchmarks/planning_pipeline/generate.py from the issue's graph
skeleton, with seeded data a few hundred rows per table. These tests check that barca reads the
whole graph, runs it cold and then from cache, invalidates exactly the steps that use an edited
helper, and keeps steps that reuse the same DuckDB names on the shared connection apart.

It also checks what barca sees when a registry's source variable is switched. The store side
(source modes, a second machine, bytes fetched, peak RSS) is in test_planning_pipeline_remote.py,
the overwrite scenarios in test_planning_pipeline_overwrite.py, and the large size is a
benchmark (benchmarks/planning_pipeline/bench.sh).
"""

from __future__ import annotations

import collections
import json
import os
import subprocess
from pathlib import Path

import pytest
from barca.api import _find_binary

from .planning_pipeline import GENERATOR, generator, write_planning_pipeline

# The table in #250.
NODES, ASSETS, TASKS, EDGES, ROOTS, LEAVES = 116, 74, 42, 262, 14, 44
LEAF_ASSETS = {"forecast_reconciled_base_units", "channel_account"}


def barca(cwd: Path, *args: str, pool: int = 4, env: dict | None = None) -> dict:
    # A bounded pool: every worker imports duckdb, pandas, polars and pyarrow.
    env = {
        **os.environ,
        "PYTHONDONTWRITEBYTECODE": "1",
        "BARCA_POOL_SIZE": str(pool),
        **(env or {}),
    }
    proc = subprocess.run(
        [_find_binary(), *args],
        cwd=cwd,
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    assert proc.returncode == 0, f"barca {' '.join(args[:1])} exit {proc.returncode}\n{proc.stderr}"
    return json.loads(proc.stdout)


def short(node_id: str) -> str:
    return node_id.split(":", 1)[1]


def run_hashes(root: Path) -> dict[str, str]:
    status = barca(root, "status", "assets.py", "--json")
    assert not status["truncated"]
    return {short(n["id"]): n["cache"]["run_hash"] for n in status["nodes"]}


# ─── The generator ────────────────────────────────────────────────────────────


def test_skeleton_matches_the_issue_table():
    gen = generator()
    nodes = gen.parse_skeleton()
    by_name = {n.name: n for n in nodes}
    kinds = collections.Counter(n.kind for n in nodes)
    assert (len(nodes), kinds["asset"], kinds["task"]) == (NODES, ASSETS, TASKS)
    edges = [(up, n, t) for n in nodes for _, t, up in n.params]
    assert len(edges) == EDGES
    hops = collections.Counter((by_name[up].returns, t) for up, _, t in edges)
    assert hops == {("R", "R"): 213, ("R", "D"): 35, ("D", "D"): 14}
    returns = collections.Counter(n.returns for n in nodes if n.kind == "asset")
    assert returns == {"R": 60, "D": 14}
    assert sum(n.polars for n in nodes) == 10
    fan_out = collections.Counter(up for up, _, _ in edges).most_common(5)
    assert [c for _, c in fan_out] == [34, 20, 17, 16, 15]
    assert fan_out[0][0] == "forecast_reconciled"
    assert [n.name for n in nodes if n.kwargs] == ["summarize_qa"]
    assert len(gen.GUARDS) == 28  # assets that fetchone() a lazy input before returning


def test_checked_in_assets_py_is_what_the_generator_writes():
    checked_in = GENERATOR.parent / "project" / "assets.py"
    assert checked_in.read_text() == generator().render_assets(), (
        "run `python benchmarks/planning_pipeline/generate.py --update`"
    )


def test_same_seed_writes_the_same_project(tmp_path):
    a = write_planning_pipeline(tmp_path / "a", seed=7).root
    b = write_planning_pipeline(tmp_path / "b", seed=7).root
    files = sorted(p.relative_to(a) for p in a.rglob("*") if p.is_file())
    assert files == sorted(p.relative_to(b) for p in b.rglob("*") if p.is_file())
    for rel in files:
        assert (a / rel).read_bytes() == (b / rel).read_bytes(), rel


# ─── barca on the graph ───────────────────────────────────────────────────────


def test_plan_and_list_read_the_whole_graph(planning_pipeline):
    root = planning_pipeline.root
    plan = barca(root, "plan", "assets.py")
    steps = [s for p in plan["phases"] for st in p["streams"] for s in st["steps"]]
    assert plan["total_steps"] == len(steps) == NODES
    assert plan["warnings"] == []

    listed = barca(root, "list", "assets.py", "--json")
    nodes = listed["nodes"]
    assert listed["total"] == len(nodes) == NODES and not listed["truncated"]
    kinds = collections.Counter(n["kind"] for n in nodes)
    assert (kinds["asset"], kinds["task"]) == (ASSETS, TASKS)
    edges = {(short(up), short(n["id"])) for n in nodes for up in n["inputs"]}
    assert len(edges) == EDGES
    assert edges == set(planning_pipeline.edges)
    used = {up for up, _ in edges}
    assert sum(not n["inputs"] for n in nodes) == ROOTS
    leaves = {short(n["id"]) for n in nodes if short(n["id"]) not in used}
    assert len(leaves) == LEAVES
    assert leaves - set(planning_pipeline.names("task")) == LEAF_ASSETS


def test_cold_run_of_every_task_then_nothing_reruns(planning_pipeline):
    root = planning_pipeline.root
    tasks = ",".join(planning_pipeline.names("task"))

    cold = barca(root, "run", tasks, "assets.py", "--json")
    assert cold["status"] == "success"
    ran = collections.Counter((s["kind"], s["status"]) for s in cold["steps"])
    # Every node except the two leaf assets is upstream of (or is) a task.
    assert ran == {("asset", "ran"): ASSETS - len(LEAF_ASSETS), ("task", "ran"): TASKS}

    first = barca(root, "get", "assets.py", "--json")
    assert {short(s["id"]) for s in first["steps"] if s["status"] == "ran"} == LEAF_ASSETS

    again = barca(root, "get", "assets.py", "--json")
    assert again["steps_executed"] == 0
    assert {s["status"] for s in again["steps"]} == {"cached"}

    # Tasks always run; no asset below them does.
    rerun = barca(root, "run", tasks, "assets.py", "--json")
    assert collections.Counter((s["kind"], s["status"]) for s in rerun["steps"]) == {
        ("asset", "cached"): ASSETS - len(LEAF_ASSETS),
        ("task", "ran"): TASKS,
    }


# Each edit, and the steps whose bodies call what it changes.
HELPER_EDITS = {
    "carryover_constant": (
        "carryover.py",
        "OPT_OUT_RATE = 0.3",
        "OPT_OUT_RATE = 0.25",
        {"carryover_account_group"},
    ),
    "drivers_one_function": (
        "drivers.py",
        '(1.0 + pl.col("rate")).max()',
        '(1.0 + 2 * pl.col("rate")).max()',
        {"launch_item_week_rate_override"},
    ),
    "drivers_shared_function": (
        "drivers.py",
        '(pl.col("value") * pl.col("rate") * sign)',
        '(pl.col("value") * pl.col("rate") * sign * 2)',
        {"driver_retirement_item", "driver_rollout_item", "driver_launch_item"},
    ),
}


@pytest.mark.parametrize("edit", sorted(HELPER_EDITS))
def test_editing_a_helper_module_invalidates_exactly_its_users(planning_pipeline, edit):
    module, old, new, users = HELPER_EDITS[edit]
    root = planning_pipeline.root
    before = run_hashes(root)
    path = root / module
    source = path.read_text()
    assert source.count(old) == 1, f"{old!r} not found once in {module}"
    path.write_text(source.replace(old, new))
    after = run_hashes(root)
    changed = {name for name in before if before[name] != after[name]}
    assert changed == planning_pipeline.downstream(users)


# Validators of the registries and the drivers built from them all stage their registry under
# the same names (`registry_rows`, `registry_frame`, `registry_keys`) on DuckDB's default
# connection, and raise if those names hold rows other than their own.
SHARED_NAME_STEPS = [
    "validate_account_exit_registry",
    "validate_carryover_registry",
    "validate_retirement_registry",
    "validate_launch_registry",
    "validate_rollout_registry",
    "validate_retirement_pipeline",
    "validate_driver_launch_item",
    "validate_driver_rollout_item",
]


@pytest.mark.parametrize("pool", [1, 4], ids=["one_worker", "four_workers"])
def test_steps_reusing_duckdb_names_do_not_see_each_others_rows(planning_pipeline, pool):
    root = planning_pipeline.root
    out = barca(root, "run", ",".join(SHARED_NAME_STEPS), "assets.py", "--json", pool=pool)
    assert out["status"] == "success"
    # Each registry names items of one group only: a driver that read another registry's rows
    # would carry items of another group.
    import pandas as pd

    status = barca(root, "status", "assets.py", "--json")
    groups = {}
    for node in status["nodes"]:
        name = short(node["id"])
        if name in ("driver_launch_item", "driver_rollout_item", "driver_retirement_item"):
            frame = pd.read_parquet(root / node["cache"]["artifact"])
            assert len(frame), name
            groups[name] = set(frame["group_id"])
    assert groups == {
        "driver_launch_item": {1},
        "driver_rollout_item": {2},
        "driver_retirement_item": {3},
    }


# ─── Registry source switches (#156, #231) ────────────────────────────────────

V2_CSV = "registries/account_exit_v2.csv"


def exited(root: Path, csv: str | None = None) -> set[int]:
    """The accounts in `exited_accounts`' current result, as barca sees it with `csv` set."""
    import pandas as pd

    env = {"ACCOUNT_EXIT_REGISTRY_CSV": csv} if csv else {}
    node = barca(root, "status", "assets.py", "--json", env=env)["nodes"]
    path = next(n for n in node if short(n["id"]) == "exited_accounts")["cache"]["artifact"]
    return set(pd.read_parquet(root / path)["account_id"])


def get_exited(root: Path, csv: str | None = None) -> dict:
    env = {"ACCOUNT_EXIT_REGISTRY_CSV": csv} if csv else {}
    out = barca(root, "get", "exited_accounts", "assets.py", "--json", env=env)
    return {short(s["id"]): s for s in out["steps"]}


def test_a_registry_source_switch_is_seen_only_when_declared(planning_pipeline):
    """The account-exit registry reads its CSV path from `ACCOUNT_EXIT_REGISTRY_CSV`.

    Undeclared, as in the original pipeline: switching the variable changes nothing barca sees.
    The step stays cached with the old rows, and no output names the variable (#574).
    Operators re-read with `--refresh`. Declared with `env=[...]`, the switch re-runs the
    registry and its consumer, and the step reports the value. A value the pipeline loads from
    its `.env` at import is the one hashed and reported, since barca reads the project's `.env`
    for a declared variable its environment does not set (#575)."""
    root = planning_pipeline.root
    (root / V2_CSV).write_text("account_id,item_id,week,rate,kind\n1,,2,1.0,exit\n2,,3,1.0,exit\n")
    first = get_exited(root)
    assert first["account_exit_registry"]["status"] == "ran"
    original = exited(root)
    assert original == {4}

    # Undeclared: not detected, not reported.
    switched = get_exited(root, V2_CSV)
    assert {s["status"] for s in switched.values()} == {"cached"}
    assert all("env" not in s for s in switched.values())
    assert exited(root) == original  # stale: the rows of the old CSV
    out = barca(
        root,
        "get",
        "exited_accounts",
        "assets.py",
        "--refresh",
        "account_exit_registry",
        "--json",
        env={"ACCOUNT_EXIT_REGISTRY_CSV": V2_CSV},
    )
    assert out["steps_executed"] == 2
    assert exited(root, V2_CSV) == {1, 2}

    # Declared: the switch changes the run hash and the value is reported.
    assets = root / "assets.py"
    source = assets.read_text()
    old = "@asset()\ndef account_exit_registry("
    assert source.count(old) == 1
    assets.write_text(
        source.replace(old, '@asset(env=["ACCOUNT_EXIT_REGISTRY_CSV"])\ndef account_exit_registry(')
    )
    declared = get_exited(root, V2_CSV)
    assert {s: declared[s]["status"] for s in declared} == {
        "account_exit_registry": "ran",
        "exited_accounts": "ran",
    }
    assert declared["account_exit_registry"]["env"] == {"ACCOUNT_EXIT_REGISTRY_CSV": V2_CSV}
    assert exited(root, V2_CSV) == {1, 2}
    back = get_exited(root, "registries/account_exit.csv")
    assert back["account_exit_registry"]["status"] == "ran"
    assert exited(root, "registries/account_exit.csv") == original

    # Declared, and switched in `.env`, which the pipeline loads at import: barca reads the value
    # from `.env` too. Unchanged, it is the value of the last run, which is served from cache.
    from_file = get_exited(root)
    assert {s["status"] for s in from_file.values()} == {"cached"}
    assert from_file["account_exit_registry"]["env"] == {
        "ACCOUNT_EXIT_REGISTRY_CSV": "registries/account_exit.csv"
    }
    dotenv = root / ".env"
    dotenv.write_text(dotenv.read_text().replace("registries/account_exit.csv", V2_CSV))
    after_edit = get_exited(root)
    # The v2 result computed above, with the variable exported, is the one for this value.
    assert {s["status"] for s in after_edit.values()} == {"cached"}
    assert after_edit["account_exit_registry"]["env"] == {"ACCOUNT_EXIT_REGISTRY_CSV": V2_CSV}
    assert exited(root) == {1, 2}
    # A value never computed before re-runs the registry and its consumer.
    v3 = "registries/account_exit_v3.csv"
    (root / v3).write_text("account_id,item_id,week,rate,kind\n3,,2,1.0,exit\n")
    dotenv.write_text(dotenv.read_text().replace(V2_CSV, v3))
    edited = get_exited(root)
    assert {s: edited[s]["status"] for s in edited} == {
        "account_exit_registry": "ran",
        "exited_accounts": "ran",
    }
    assert edited["account_exit_registry"]["env"] == {"ACCOUNT_EXIT_REGISTRY_CSV": v3}
    assert exited(root) == {3}
